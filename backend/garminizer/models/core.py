"""Athlete, devices, gear, raw API payloads and app settings."""

from __future__ import annotations

from datetime import date, datetime
from typing import Any

from sqlalchemy import ForeignKey, Index, UniqueConstraint, func, text
from sqlalchemy.orm import Mapped, mapped_column

from garminizer.db.base import Base, Big, Day, Real, Small, TsTz


class Athlete(Base):
    """The one athlete this installation belongs to (single-user app)."""

    __tablename__ = "athlete"
    __table_args__ = {"comment": "The athlete profile (one row; id is always 1)."}

    id: Mapped[Small] = mapped_column(primary_key=True, server_default=text("1"))
    profile_id: Mapped[Big | None] = mapped_column(comment="Garmin user profile number")
    display_name: Mapped[str | None]
    full_name: Mapped[str | None]
    gender: Mapped[str | None]
    birth_date: Mapped[date | None]
    height_cm: Mapped[Real | None]
    weight_kg: Mapped[Real | None]
    max_hr: Mapped[Small | None]
    resting_hr: Mapped[Small | None]
    lactate_threshold_hr: Mapped[Small | None]
    lactate_threshold_speed_mps: Mapped[Real | None]
    ftp_w: Mapped[Small | None] = mapped_column(comment="Functional threshold power (cycling)")
    vo2max_running: Mapped[Real | None]
    vo2max_cycling: Mapped[Real | None]
    unit_system: Mapped[str] = mapped_column(server_default="metric", comment="metric | statute")
    time_zone: Mapped[str | None] = mapped_column(comment="IANA zone, e.g. Europe/Berlin")
    hr_zones: Mapped[list[Any] | None] = mapped_column(comment="Heart-rate zone floors (bpm)")
    power_zones: Mapped[list[Any] | None] = mapped_column(comment="Power zone floors (W)")
    is_demo: Mapped[bool] = mapped_column(
        server_default="false", comment="True when generated by `garminizer demo seed`"
    )
    updated_at: Mapped[TsTz] = mapped_column(server_default=func.now())


class Device(Base):
    __tablename__ = "device"
    __table_args__ = {"comment": "Garmin devices that recorded data."}

    device_id: Mapped[Big] = mapped_column(primary_key=True)
    product_name: Mapped[str | None]
    display_name: Mapped[str | None]
    software_version: Mapped[str | None]
    is_primary: Mapped[bool] = mapped_column(server_default="false")
    last_used_at: Mapped[TsTz | None]
    image_url: Mapped[str | None]


class Gear(Base):
    __tablename__ = "gear"
    __table_args__ = {"comment": "Shoes, bikes and other equipment tracked in Garmin Connect."}

    uuid: Mapped[str] = mapped_column(primary_key=True)
    gear_type: Mapped[str] = mapped_column(comment="shoes | bike | other")
    display_name: Mapped[str | None]
    make: Mapped[str | None]
    model: Mapped[str | None]
    status: Mapped[str] = mapped_column(server_default="active", comment="active | retired")
    date_begin: Mapped[Day | None]
    date_end: Mapped[Day | None]
    max_distance_m: Mapped[float | None] = mapped_column(comment="Retirement threshold")
    total_distance_m: Mapped[float | None]
    total_activities: Mapped[int | None]


class ActivityGear(Base):
    __tablename__ = "activity_gear"
    __table_args__ = {"comment": "Which gear was used in which activity."}

    activity_id: Mapped[Big] = mapped_column(
        ForeignKey("activity.activity_id", ondelete="CASCADE"), primary_key=True
    )
    gear_uuid: Mapped[str] = mapped_column(
        ForeignKey("gear.uuid", ondelete="CASCADE"), primary_key=True
    )


class RawPayload(Base):
    """Every Garmin API response, verbatim. Typed tables can always be rebuilt from here."""

    __tablename__ = "raw_payload"
    __table_args__ = (
        UniqueConstraint("dataset", "key"),
        Index(None, "parsed_at", postgresql_where=text("parsed_at IS NULL")),
        {"comment": "Verbatim Garmin API responses; `garminizer reparse` rebuilds from these."},
    )

    id: Mapped[Big] = mapped_column(primary_key=True, autoincrement=True)
    dataset: Mapped[str] = mapped_column(comment="Logical dataset, e.g. sleep, activity_details")
    key: Mapped[str] = mapped_column(comment="Day (YYYY-MM-DD), activity id or range key")
    endpoint: Mapped[str] = mapped_column(comment="Client method that produced the payload")
    fetched_at: Mapped[TsTz] = mapped_column(server_default=func.now())
    sha256: Mapped[str]
    payload: Mapped[dict[str, Any] | None] = mapped_column(comment="JSON body (null = empty)")
    parsed_at: Mapped[TsTz | None]
    parse_error: Mapped[str | None]


class AppSetting(Base):
    __tablename__ = "app_setting"
    __table_args__ = {"comment": "Key/value settings changed from the UI."}

    key: Mapped[str] = mapped_column(primary_key=True)
    value: Mapped[dict[str, Any]]
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now())
